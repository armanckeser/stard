const SIZE = 64;

/** A round badge in `color` with the icon in dark ink, and `count` beside it when given (the texture is then twice as wide). */
export function iconTexture(icon: keyof typeof PATHS, color: string, count?: number): THREE.CanvasTexture {
  const canvas = document.createElement("canvas");
  canvas.width = count === undefined ? SIZE : SIZE * 2;
  canvas.height = SIZE;
  const pen = canvas.getContext("2d")!;
  pen.fillStyle = color;
  pen.beginPath();
  pen.roundRect(2, 2, canvas.width - 4, SIZE - 4, SIZE / 2 - 2);
  pen.fill();
  pen.fillStyle = "#0b0f14";
  pen.save();
  pen.translate(14, 14);
  pen.scale(36 / 16, 36 / 16);
  for (const d of PATHS[icon]) pen.fill(new Path2D(d));
  pen.restore();
  if (count !== undefined) {
    pen.font = "800 38px system-ui, sans-serif";
    pen.textBaseline = "middle";
    pen.fillText(String(count), SIZE + 2, SIZE / 2 + 2);
  }
  const texture = new THREE.CanvasTexture(canvas);
  texture.colorSpace = THREE.SRGBColorSpace;
  return texture;
}
